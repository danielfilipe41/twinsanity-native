#!/usr/bin/env python3
"""Generates the SMAA look-up texture headers in src/platform/sdl3/graphics/shaders/.

SMAA's area and search textures are computed, not authored: the reference implementation ships
AreaTex.py and SearchTex.py (vendored here verbatim from https://github.com/iryoku/smaa, MIT
licence), which print the byte arrays their own headers carry. This runs both and rewrites
smaa_area_tex.bin.h and smaa_search_tex.bin.h in the hex dump format the bgfx blobs beside them
use (tools/build_shaders.py), so the textures are regenerable rather than pasted in.

The area texture is generated as R8G8 upstream; the header is RGBA8 because that is what the
sampler takes, with the two area channels in R and G, B zero and A opaque. The search texture is
R8 either way.

    python3 tools/smaa/build_smaa_textures.py           # regenerate the headers
    python3 tools/smaa/build_smaa_textures.py --check    # verify them (no writes)

Both generators need Pillow; AreaTex.py brute-forces its diagonal areas and takes about a minute.
"""
import importlib.util
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SHADERS = ROOT / "src" / "platform" / "sdl3" / "graphics" / "shaders"

# Width and height the shaders sample these at; the generators hard-code them too, but the array
# sizes below are what the headers declare, so a shape change here means the shaders change.
AREA_WIDTH, AREA_HEIGHT = 160, 560
SEARCH_WIDTH, SEARCH_HEIGHT = 64, 16

# One line per texture: the array the header declares, the channels the generator prints and the
# channels the header stores, and the comment above the array.
TEXTURES = {
    "smaa_area_tex.bin.h": {
        "array": "smaa_area_tex",
        "script": "AreaTex.py",
        "width": AREA_WIDTH,
        "height": AREA_HEIGHT,
        "channels": 4,
        "generatedChannels": 2,
        "comment": [
            "SMAA area lookup texture, %dx%d RGBA8: R and G are the coverage areas at the left and" %
            (AREA_WIDTH, AREA_HEIGHT),
            "right end of the edge pattern the texel's coordinates select, B is zero and A is opaque.",
            "Generated by tools/smaa/build_smaa_textures.py from SMAA by Jorge Jimenez (MIT,",
            "https://github.com/iryoku/smaa).",
        ],
    },
    "smaa_search_tex.bin.h": {
        "array": "smaa_search_tex",
        "script": "SearchTex.py",
        "width": SEARCH_WIDTH,
        "height": SEARCH_HEIGHT,
        "channels": 1,
        "generatedChannels": 1,
        "comment": [
            "SMAA search lookup texture, %dx%d R8: each texel holds how many pixels the last step of" %
            (SEARCH_WIDTH, SEARCH_HEIGHT),
            "the line search advances for the edge pattern its coordinates select.",
            "Generated by tools/smaa/build_smaa_textures.py from SMAA by Jorge Jimenez (MIT,",
            "https://github.com/iryoku/smaa).",
        ],
    },
}


def RunGenerator(script: str, directory: Path) -> bytes:
    """Runs one vendored generator in a scratch directory and returns the byte array it prints. The
    generators save .tga previews next to their cwd, which is why that cwd is a temporary one."""
    result = subprocess.run([sys.executable, str(HERE / script)], cwd=directory, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"{script} failed:\n{result.stderr}")
    # Each generator prints exactly one brace-delimited list, the array its own header carries; the
    # .tga previews go to disk, so nothing else lands on stdout to confuse the parse.
    body = result.stdout.split("{", 1)[1].split("}", 1)[0]
    return bytes(int(value, 16) for value in re.findall(r"0x[0-9a-fA-F]{2}", body))


def ToRGBA8(rg: bytes) -> bytes:
    """Widens the generator's interleaved R8G8 texels to the RGBA8 texels the sampler reads."""
    rgba = bytearray(len(rg) // 2 * 4)
    rgba[0::4] = rg[0::2]
    rgba[1::4] = rg[1::2]
    rgba[2::4] = bytes(len(rg) // 2)
    rgba[3::4] = b"\xff" * (len(rg) // 2)
    return bytes(rgba)


def Format(array: str, data: bytes, comment: list) -> str:
    """Renders one header the way shaderc's --bin2c does: 16 bytes per line, tab indented, the
    printable characters of the line as a trailing comment aligned in the same column."""
    lines = [f"// {line}" for line in comment]
    lines.append(f"static const uint8_t {array}[{len(data)}] =")
    lines.append("{")
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        hexBytes = "".join(f"0x{value:02x}, " for value in chunk)
        text = "".join(chr(value) if 32 <= value < 127 else "." for value in chunk)
        lines.append("\t" + hexBytes.ljust(96) + f"// {text}")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    arguments = sys.argv[1:]
    check = "--check" in arguments

    if importlib.util.find_spec("PIL") is None:
        raise SystemExit("the vendored SMAA generators need Pillow: pip install pillow")

    failed = False
    with tempfile.TemporaryDirectory() as scratch:
        for name, texture in TEXTURES.items():
            data = RunGenerator(texture["script"], Path(scratch))
            if len(data) != texture["width"] * texture["height"] * texture["generatedChannels"]:
                raise SystemExit(f"{name}: {texture['script']} produced {len(data)} bytes, not the expected texture")
            if texture["channels"] == 4:
                data = ToRGBA8(data)
            header = Format(texture["array"], data, texture["comment"])
            target = SHADERS / name

            if check:
                same = target.read_text() == header if target.is_file() else False
                print(f"{texture['array']}: {'ok' if same else 'STALE (regenerate)'}")
                failed |= not same
            else:
                target.write_text(header)
                print(f"{texture['array']}: wrote {name} ({len(data)} bytes)")

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
